let fixedCount = 0;

for (const art of rawDb.articles) {
  // Apply specific title & summary updates
  if (titleFixes[art.id]) {
    const fix = titleFixes[art.id];
    art.title = fix.title;
    art.slug = createBengaliSlug(fix.title, art.id);
    if (fix.summary) art.summary = fix.summary;
    fixedCount++;
  }

  // Fix image fallbacks
  if (!art.imageUrl || art.imageUrl === 'undefined') {
    if (art.images && art.images.length > 0 && art.images[0] && art.images[0] !== 'undefined') {
      art.imageUrl = art.images[0];
    } else {
      art.imageUrl = '/images/og-image.png';
    }
  }

  if (art.images) {
    art.images = art.images.filter(img => img && img !== 'undefined');
    if (art.images.length === 0 && art.imageUrl) {
      art.images = [art.imageUrl];
    }
  }

  // Clean trailing punctuation / ellipsis in titles
  if (art.title) {
    art.title = art.title.replace(/\.{2,}$/, '').replace(/…$/, '').replace(/,+$/, '').trim();
  }

  // Content Paragraph & Headline Formatting Improvements
  if (art.content) {
    let cleaned = art.content;

    // 1. Remove weird isolated hashtags or trailing social media tokens
    cleaned = cleaned.replace(/[\r\n]+\s*#\s*[\r\n]+/g, '\n\n');
    cleaned = cleaned.replace(/[\r\n]+\s*WeatherUpdate\s*[\r\n]+/g, '\n\n');
    cleaned = cleaned.replace(/undefined/g, '');

    // 2. Normalize markdown headings: ensure blank lines before ## and ###
    cleaned = cleaned.replace(/([^\n])\n(#{2,4}\s+[^\n]+)/g, '$1\n\n$2');
    cleaned = cleaned.replace(/(#{2,4}\s+[^\n]+)\n([^\n#])/g, '$1\n\n$2');

    // 3. Remove excessive repeated blank lines
    cleaned = cleaned.replace(/\n{3,}/g, '\n\n').trim();

    art.content = cleaned;
  }

  // Clean and ensure punchy summary
  if (!art.summary || art.summary.length < 30) {
    const firstPara = (art.content || '').split('\n\n')[0].replace(/[#*`]/g, '').trim();
    art.summary = firstPara.length > 160 ? firstPara.slice(0, 157) + '...' : firstPara;
  } else {
    // Strip raw newlines or quotes from summary
    art.summary = art.summary.replace(/[\r\n]+/g, ' ').replace(/["']/g, '').trim();
  }
}

fs.writeFileSync(DATA_PATH, JSON.stringify(rawDb, null, 2), 'utf-8');
console.log(`✓ Data cleanup complete! Fixed specific mapped titles: ${fixedCount}. Formatted all ${rawDb.articles.length} articles.`);
