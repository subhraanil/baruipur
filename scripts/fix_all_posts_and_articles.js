// Helper to create clean Bengali slugs
function createBengaliSlug(headline, id) {
  const clean = headline
    .replace(/[^\u0980-\u09FFa-zA-Z0-9\s-]/g, '')
    .trim()
    .replace(/\s+/g, '-')
    .substring(0, 75);
  const suffix = id.split('-').pop();
  return clean ? `${clean}-${suffix}` : `news-${id}`;
}

