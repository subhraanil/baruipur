let updatedCount = 0;
for (const art of articlesToPublish) {
  const idx = db.articles.findIndex(a => a.id === art.id);
  if (idx !== -1) {
    db.articles[idx] = {
      ...db.articles[idx],
      ...art
    };
    updatedCount++;
    console.log(`Updated draft to published: ${art.id} -> ${art.slug}`);
  } else {
    db.articles.unshift(art);
    updatedCount++;
    console.log(`Inserted new published article: ${art.id} -> ${art.slug}`);
  }
}

// Ensure unique slugs
const slugMap = new Map();
for (const a of db.articles) {
  if (slugMap.has(a.slug) && slugMap.get(a.slug) !== a.id) {
    a.slug = `${a.slug}-${a.id.slice(-4)}`;
  }
  slugMap.set(a.slug, a.id);
}

fs.writeFileSync(DATA_PATH, JSON.stringify(db, null, 2), 'utf-8');
console.log(`Successfully published ${updatedCount} articles! Total articles in DB: ${db.articles.length}`);
