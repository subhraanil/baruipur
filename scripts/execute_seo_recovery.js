// Helper to normalize and match URL to article
function matchArticle(urlStr) {
  const rawPath = urlStr.replace('https://baruipur.online/', '').replace(/\/$/, '');
  const decoded = decodeURIComponent(rawPath);
  return newsData.articles.find(a => 
    a.slug === decoded || 
    a.slug === rawPath ||
    a.id === decoded || 
    (a.aliases && (a.aliases.includes(decoded) || a.aliases.includes(rawPath))) ||
    (a.title && (a.title.includes(decoded.slice(0, 20)) || decoded.includes(a.title.slice(0, 20))))
  );
}

