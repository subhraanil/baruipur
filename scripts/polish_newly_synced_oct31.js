// Apply updates
let publishedCount = 0;
for (const [id, updateData] of Object.entries(updates)) {
  const existingIdx = rawDb.articles.findIndex(a => a.id === id);
  if (existingIdx >= 0) {
    const orig = rawDb.articles[existingIdx];
    rawDb.articles[existingIdx] = {
      ...orig,
      ...updateData,
      slug: updateData.slug || createBengaliSlug(updateData.title, id),
      publishedAt: new Date().toISOString()
    };
    publishedCount++;
    console.log(`[POLISHED & PUBLISHED] ${id} -> "${updateData.title.slice(0, 50)}..."`);
  } else {
    const newArt = {
      id,
      ...updateData,
      slug: updateData.slug || createBengaliSlug(updateData.title, id),
      publishedAt: new Date().toISOString(),
      views: Math.floor(Math.random() * 40) + 15
    };
    rawDb.articles.unshift(newArt);
    publishedCount++;
    console.log(`[CREATED & PUBLISHED] ${id} -> "${updateData.title.slice(0, 50)}..."`);
  }
}

